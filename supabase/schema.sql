-- Clustering (#2): corroborating sources; Grounding (#3): official source;
-- Re-verification (#7): when we last re-checked an open case.
ALTER TABLE public.enforcement_actions
    ADD COLUMN IF NOT EXISTS sources JSONB DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS official_source_url TEXT,
    ADD COLUMN IF NOT EXISTS last_reverified_at TIMESTAMPTZ;

-- Feedback loop (#4): every reviewer verify/discard becomes training signal.
CREATE TABLE IF NOT EXISTS public.review_decisions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id   TEXT,
    decision    TEXT NOT NULL CHECK (decision IN ('verified', 'discarded')),
    title       TEXT,
    snippet     TEXT,
    source_url  TEXT,
    signature   TEXT,                 -- normalised company|authority for FP memory
    fields      JSONB DEFAULT '{}'::jsonb,
    decided_at  TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_decisions_decided ON public.review_decisions(decided_at DESC);
CREATE INDEX IF NOT EXISTS idx_decisions_sig ON public.review_decisions(signature);

-- Weekly executive brief (#6).
CREATE TABLE IF NOT EXISTS public.intel_briefs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period      TEXT NOT NULL,         -- e.g. 2026-W38
    markdown    TEXT NOT NULL,
    stats       JSONB DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_briefs_period ON public.intel_briefs(period);

-- Story -> content angle (#9).
CREATE TABLE IF NOT EXISTS public.content_angles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_url     TEXT UNIQUE,
    headline      TEXT,
    angle         TEXT NOT NULL,
    target_keyword TEXT,
    rationale     TEXT,
    score         INT DEFAULT 0,
    created_at    TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_angles_created ON public.content_angles(created_at DESC);

ALTER TABLE public.review_decisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.intel_briefs     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.content_angles   ENABLE ROW LEVEL SECURITY;

-- Reviewers may log decisions and read the intelligence outputs.
DROP POLICY IF EXISTS dec_admin_all ON public.review_decisions;
CREATE POLICY dec_admin_all ON public.review_decisions
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS briefs_admin_read ON public.intel_briefs;
CREATE POLICY briefs_admin_read ON public.intel_briefs
    FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS angles_admin_read ON public.content_angles;
CREATE POLICY angles_admin_read ON public.content_angles
    FOR SELECT TO authenticated USING (true);

-- The weekly brief is safe to expose publicly (aggregate, no PII).
DROP POLICY IF EXISTS briefs_public_read ON public.intel_briefs;
CREATE POLICY briefs_public_read ON public.intel_briefs
    FOR SELECT TO anon USING (true);
